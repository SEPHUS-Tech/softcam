#!/usr/bin/env bash
# Check commit subjects against Conventional Commits.
#
#   ./scripts/checks/check_commits.sh [<range>]      default: origin/main..HEAD, else the last commit
#   ./scripts/checks/check_commits.sh --subject <s>  check one subject, such as a pull request title
#
# This is a gate rather than a style preference: release notes are generated from these subjects by
# git-cliff, so a subject that does not parse is a defect in the release, not an untidy log line.
# A squash merge makes the pull request title the subject on main, so the title is checked too.
#
# Deliberately plain shell. commitlint would work but needs node and two npm packages to check a
# regular expression.
set -uo pipefail

# The types git-cliff groups on, plus revert, which git itself generates.
TYPES='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'
# The code standards set no length limit, so a longer subject is a warning, not a failure.
SUBJECT_MAX=72

# Prints a failure and returns 1 when the subject is not a Conventional Commit; warns when it is
# longer than SUBJECT_MAX. Scopes may be upper case (`docs(LOOR-215): …`), and git's own revert
# subject (`Revert "feat: …"`, and `Reapply "…"` for a revert of a revert) is accepted.
check_subject() {
  local id="$1" subject="$2"
  if ! printf '%s' "$subject" | grep -qE "^($TYPES)(\([A-Za-z0-9._/,-]+\))?!?: .+" &&
     ! printf '%s' "$subject" | grep -qE '^(Revert|Reapply) ".+"$'; then
    printf 'FAIL %s  not a Conventional Commit subject\n     %s\n' "$id" "$subject"
    return 1
  fi
  if [ "${#subject}" -gt "$SUBJECT_MAX" ]; then
    printf '::warning::%s subject is %d characters, over %d: %s\n' \
      "$id" "${#subject}" "$SUBJECT_MAX" "$subject"
  fi
  return 0
}

if [ "${1:-}" = "--subject" ]; then
  [ "$#" -eq 2 ] || { echo "usage: $0 --subject <subject>"; exit 2; }
  check_subject "title" "$2" && echo "ok  title"
  exit
fi

# The default branch is RESOLVED, not assumed. Hardcoding origin/main means that on a repository
# whose trunk is master, develop or trunk, this silently falls through to the single-commit range
# and reports green having checked one subject out of a whole pull request.
default_branch() {
  local ref
  ref="$(git symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null)" && {
    printf '%s' "$ref"; return 0
  }
  for ref in origin/main origin/master origin/trunk origin/develop; do
    git rev-parse --verify --quiet "$ref" >/dev/null 2>&1 && { printf '%s' "$ref"; return 0; }
  done
  return 1
}

range="${1:-}"
if [ -z "$range" ]; then
  if base="$(default_branch)" &&
     [ "$(git rev-parse HEAD)" != "$(git rev-parse "$base")" ]; then
    range="$base..HEAD"
  else
    # No remote, or HEAD is the branch tip itself. One commit is all there is to check.
    range="HEAD~1..HEAD"
  fi
fi

# An unreadable range (a base that was not fetched, a typo) makes git log print nothing,
# which would otherwise pass with zero subjects checked.
if ! git rev-list "$range" >/dev/null 2>&1; then
  echo "FAIL cannot read the commit range $range"
  exit 1
fi

fail=0
checked=0
while IFS= read -r line; do
  [ -n "$line" ] || continue
  sha="${line%% *}"
  subject="${line#* }"
  # A merge commit's subject is generated by git and is not a Conventional Commit.
  if [ "$(git rev-list --no-walk --count --merges "$sha" 2>/dev/null)" = "1" ]; then
    continue
  fi
  checked=$((checked + 1))
  check_subject "${sha:0:8}" "$subject" || fail=1
done < <(git log --format='%H %s' "$range" 2>/dev/null)

if [ "$checked" = 0 ]; then
  echo "no non-merge commits in range $range"
  exit 0
fi
[ "$fail" = 0 ] && echo "ok  $checked commit subject(s) in $range"
exit "$fail"
